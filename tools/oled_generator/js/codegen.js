// ─── Vector / Primitive Code Generation ──────────────────────────────────────
// Lopaka-style hybrid: hand-drawn shapes + classic-font text become GFX
// primitive calls (drawLine/drawRect/drawCircle/println). Everything else
// (freehand, fills, icons, imported images, unmatched frames) is packed into a
// residual drawBitmap so the output is always pixel-faithful.

function escapeCString(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

// A text layer can only be emitted as primitive text when it uses the classic
// 5x7 editor font (which matches Adafruit's built-in font at size 1).
function textIsVectorizable(layer, library) {
  return (library === 'adafruit' || library === 'sh110x')
    && layer.type === 'text'
    && layer.geo
    && (layer.geo.fontKey === '5x7');
}

function layerIsVectorizable(layer, library) {
  if (!layer || !layer.geo) return false;
  if (layer.type === 'line' || layer.type === 'rect' || layer.type === 'circle') return true;
  if (layer.type === 'text') return textIsVectorizable(layer, library);
  return false;
}

// Layers confirmed to be fully present (every pixel ON) in a specific frame.
// This makes multi-frame/animation export safe: a layer only turns into a
// primitive on the frames where it actually appears, otherwise it stays bitmap.
function vectorLayersForFrame(layers, frame, library) {
  const present = [];
  for (const layer of (layers || [])) {
    if (!layerIsVectorizable(layer, library)) continue;
    const px = layer.pixels || [];
    if (!px.length) continue;
    if (px.every(([x, y]) => frame[y] && frame[y][x])) present.push(layer);
  }
  return present;
}

// Frame pixels minus the pixels claimed by vector layers → residual bitmap.
function residualFrameFor(frame, presentLayers, width, height) {
  const res = frame.map(row => row.slice());
  for (const layer of presentLayers) {
    for (const [x, y] of layer.pixels) {
      if (res[y] && x < width) res[y][x] = 0;
    }
  }
  let any = false;
  for (let y = 0; y < height && !any; y++)
    for (let x = 0; x < width; x++) if (res[y][x]) { any = true; break; }
  return { frame: res, hasPixels: any };
}

function adafruitVectorCalls(present, residualName, hasResidual, color = 'SSD1306_WHITE') {
  const COLOR = color;
  const lines = [];
  if (hasResidual) lines.push(`  display.drawBitmap(0, 0, ${residualName}, SCREEN_WIDTH, SCREEN_HEIGHT, ${COLOR});`);
  for (const layer of present) {
    const g = layer.geo;
    if (layer.type === 'line') {
      lines.push(`  display.drawLine(${g.x1}, ${g.y1}, ${g.x2}, ${g.y2}, ${COLOR});`);
    } else if (layer.type === 'rect') {
      lines.push(`  display.${g.fill ? 'fillRect' : 'drawRect'}(${g.x}, ${g.y}, ${g.w}, ${g.h}, ${COLOR});`);
    } else if (layer.type === 'circle') {
      lines.push(`  display.${g.fill ? 'fillCircle' : 'drawCircle'}(${g.cx}, ${g.cy}, ${g.r}, ${COLOR});`);
    } else if (layer.type === 'text') {
      lines.push(`  display.setTextColor(${COLOR});`);
      lines.push(`  display.setTextSize(1);`);
      lines.push(`  display.setCursor(${g.x}, ${g.y});`);
      lines.push(`  display.println("${escapeCString(g.content)}");`);
    }
  }
  return lines.join('\n');
}

function u8g2VectorCalls(present, residualName, hasResidual) {
  const lines = [];
  if (hasResidual) lines.push(`  u8g2.drawXBMP(0, 0, SCREEN_WIDTH, SCREEN_HEIGHT, ${residualName});`);
  for (const layer of present) {
    const g = layer.geo;
    if (layer.type === 'line') {
      lines.push(`  u8g2.drawLine(${g.x1}, ${g.y1}, ${g.x2}, ${g.y2});`);
    } else if (layer.type === 'rect') {
      lines.push(`  u8g2.${g.fill ? 'drawBox' : 'drawFrame'}(${g.x}, ${g.y}, ${g.w}, ${g.h});`);
    } else if (layer.type === 'circle') {
      lines.push(`  u8g2.${g.fill ? 'drawDisc' : 'drawCircle'}(${g.cx}, ${g.cy}, ${g.r});`);
    }
  }
  return lines.join('\n');
}

function generateVectorArduino(frames, layers, display, board, addr, isAnim, fps, library) {
  const { width, height } = display;
  const board_info = BOARDS[board];
  const isU8g2 = library === 'u8g2';
  const af = !isU8g2 ? adafruitLibMeta(display, library) : null;

  const declarations = [];
  const renderFns = [];

  frames.forEach((frame, i) => {
    const present = vectorLayersForFrame(layers, frame, library === 'u8g2' ? 'u8g2' : 'adafruit');
    const { frame: resFrame, hasPixels } = residualFrameFor(frame, present, width, height);
    let residualName = '';
    if (hasPixels) {
      residualName = `frameRes${i}`;
      const bytes = packBitmap(resFrame, width, height);
      declarations.push(isU8g2
        ? `const uint8_t ${residualName}[] PROGMEM = {\n${formatBytes(bytes)}\n};\n${frameCreditC()}`
        : `const uint8_t PROGMEM ${residualName}[${bytes.length}] = {\n${formatBytes(bytes)}\n};\n${frameCreditC()}`);
    }
    const calls = isU8g2
      ? u8g2VectorCalls(present, residualName, hasPixels)
      : adafruitVectorCalls(present, residualName, hasPixels, af.color);

    const body = isU8g2
      ? `void renderFrame${i}() {\n  u8g2.clearBuffer();\n${calls}\n  u8g2.sendBuffer();\n}`
      : `void renderFrame${i}() {\n  display.clearDisplay();\n${calls}\n  display.display();\n}`;
    renderFns.push(body);
  });

  const rendererList = `{${frames.map((_, i) => `renderFrame${i}`).join(', ')}}`;
  const period = Math.round(1000 / fps);

  let loopBody;
  if (isAnim) {
    loopBody = `
  static uint8_t idx = 0;
  static unsigned long t = 0;
  void (*renderers[])() = ${rendererList};
  if (millis() - t >= ${period}) {
    t = millis();
    renderers[idx]();
    idx = (idx + 1) % ${frames.length};
  }`;
  } else {
    loopBody = `
  static bool drawn = false;
  if (!drawn) { renderFrame0(); drawn = true; }`;
  }

  if (isU8g2) {
    const u8g2Ctor = u8g2Constructor(display, board, 'u8g2');
    return `/*
 * ${CODEGEN_ATTR}
 * Board : ${board_info.name}
 * I2C   : SDA ${board_info.sda}, SCL ${board_info.scl}
 * Display: ${display.name} @ ${addr}
 * Library: U8g2 (vector / primitives)
 *
${codegenSocialC()}
 */

#include <U8g2lib.h>
#include <Wire.h>

#define SCREEN_WIDTH  ${width}
#define SCREEN_HEIGHT ${height}

${u8g2Ctor}

${declarations.join('\n\n')}

${renderFns.join('\n\n')}

void setup() {
${sketchWireSetup(board)}  u8g2.begin();
  u8g2.setI2CAddress(${addr} << 1);
}

void loop() {${loopBody}
}
`;
  }

  return `/*
 * ${CODEGEN_ATTR}
 * Board : ${board_info.name}
 * I2C   : SDA ${board_info.sda}, SCL ${board_info.scl}
 * Display: ${display.name} @ ${addr}
 * Library: ${af.libLabel} (vector / primitives)
 *
${codegenSocialC()}
 */

#include <Wire.h>
#include <Adafruit_GFX.h>
#include <${af.include}>

#define SCREEN_WIDTH  ${width}
#define SCREEN_HEIGHT ${height}
#define OLED_RESET    -1
#define SCREEN_ADDR   ${addr}

${af.className} display(SCREEN_WIDTH, SCREEN_HEIGHT, &Wire, OLED_RESET);

${declarations.join('\n\n')}

${renderFns.join('\n\n')}

void setup() {
  Serial.begin(115200);
${sketchWireSetup(board)}  if (!display.${af.beginExpr('SCREEN_ADDR')}) {
    Serial.println(F("${af.sh ? 'SH1106' : 'SSD1306'} allocation failed"));
    for (;;);
  }
  display.clearDisplay();
  display.display();
}

void loop() {${loopBody}
}
`;
}

function generateVectorMicroPython(frames, layers, display, board, addr, isAnim, fps) {
  const { width, height } = display;
  const board_info = BOARDS[board];
  const addrInt = parseInt(addr, 16);

  const declarations = [];
  const renderFns = [];

  frames.forEach((frame, i) => {
    // MicroPython framebuf has no built-in 5x7 text match → text stays bitmap.
    const present = vectorLayersForFrame(layers, frame, 'micropython-shapes')
      .filter(l => l.type !== 'text');
    const { frame: resFrame, hasPixels } = residualFrameFor(frame, present, width, height);
    const body = [`def render_frame_${i}():`, `    display.fill(0)`];
    if (hasPixels) {
      const bytes = packBitmap(resFrame, width, height);
      declarations.push(`frameRes${i} = bytearray([${bytes.join(', ')}])
${frameCreditPy()}`);
      body.push(`    buf = framebuf.FrameBuffer(frameRes${i}, ${width}, ${height}, framebuf.MONO_HLSB)`);
      body.push(`    display.blit(buf, 0, 0)`);
    }
    for (const layer of present) {
      const g = layer.geo;
      if (layer.type === 'line') body.push(`    display.line(${g.x1}, ${g.y1}, ${g.x2}, ${g.y2}, 1)`);
      else if (layer.type === 'rect') body.push(`    display.${g.fill ? 'fill_rect' : 'rect'}(${g.x}, ${g.y}, ${g.w}, ${g.h}, 1)`);
      else if (layer.type === 'circle') body.push(`    display.ellipse(${g.cx}, ${g.cy}, ${g.r}, ${g.r}, 1${g.fill ? ', True' : ''})`);
    }
    body.push(`    display.show()`);
    renderFns.push(body.join('\n'));
  });

  const loop = isAnim
    ? `import time\nrenderers = [${frames.map((_, i) => `render_frame_${i}`).join(', ')}]\nidx = 0\nwhile True:\n    renderers[idx]()\n    idx = (idx + 1) % len(renderers)\n    time.sleep(${(1 / fps).toFixed(3)})`
    : `render_frame_0()`;

  return `# ${CODEGEN_ATTR}
# Board  : ${board_info.name}
# Display: ${display.name} @ ${addr}  (vector / primitives)
# Note: framebuf.ellipse() needs a recent MicroPython build.
#
${codegenSocialPy()}

from machine import Pin, I2C
import ssd1306
import framebuf

i2c = I2C(0, scl=Pin(${board_info.scl}), sda=Pin(${board_info.sda}))
display = ssd1306.SSD1306_I2C(${width}, ${height}, i2c, addr=${addrInt})

${declarations.join('\n')}

${renderFns.join('\n\n')}

${loop}
`;
}

function generateVectorCode(frames, layers, config) {
  const display = DISPLAYS[config.display];
  const { board, library, language, address, fps } = config;
  const isAnim = frames.length > 1;
  if (language === 'micropython') {
    return generateVectorMicroPython(frames, layers, display, board, address, isAnim, fps);
  }
  return generateVectorArduino(frames, layers, display, board, address, isAnim, fps, library || 'adafruit');
}

