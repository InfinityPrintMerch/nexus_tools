function boardIdOf(board) {
  if (!board) return '';
  return typeof board === 'string' ? board : (board.id || '');
}

function wireBeginLines(board) {
  const info = BOARDS[boardIdOf(board)];
  if (info && info.explicitWire && info.sda != null && info.scl != null) {
    const numeric = /^\d+$/.test(String(info.sda)) && /^\d+$/.test(String(info.scl));
    const setPins = numeric
      ? `#if defined(ESP32)\n  Wire.setPins(${info.sda}, ${info.scl});\n#endif\n`
      : '';
    return `${setPins}  Wire.begin(${info.sda}, ${info.scl});\n  delay(100);`;
  }
  return '  Wire.begin();\n  delay(100);';
}

function sketchWireSetup(board) {
  const info = BOARDS[boardIdOf(board)];
  if (!info || !info.explicitWire) return '';
  return wireBeginLines(board) + '\n';
}

function u8g2Constructor(display, board, varName) {
  const info = BOARDS[boardIdOf(board)];
  const extra = (info && info.explicitWire && info.sda != null)
    ? `, ${info.scl}, ${info.sda}`
    : '';
  return `${u8g2ClassName(display)} ${varName}(U8G2_R0, /* reset=*/ U8X8_PIN_NONE${extra});`;
}

