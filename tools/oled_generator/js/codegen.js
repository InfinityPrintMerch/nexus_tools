function generateWifiReceiverCode(config) {
  const display = DISPLAYS[config.display];
  const board = BOARDS[config.board];
  if (!display || !board) {
    return { supported: false, code: '', label: 'WiFi receiver', hint: 'Select a valid board and display.' };
  }

  if (!wifiBoardSupported(config.board)) {
    return {
      supported: false,
      code: '',
      label: 'WiFi receiver',
      hint: 'Wireless live preview needs an ESP8266, ESP32, or Seeed XIAO ESP32 board.',
    };
  }

  if (config.language === 'micropython') {
    return {
      supported: false,
      code: '',
      label: 'WiFi receiver',
      hint: 'Switch to Arduino for WiFi live preview on ESP boards.',
    };
  }

  if (config.mode === 'dual') {
    return {
      supported: false,
      code: '',
      label: 'WiFi receiver',
      hint: 'Dual-screen WiFi preview is not available yet. Use Single Screen or USB Connect for dual OLED.',
    };
  }

  const libOk = config.library === 'adafruit' || config.library === 'sh110x';
  const driverOk = display.driver === 'SSD1306' || display.driver === 'SH1106';
  if (!driverOk || !libOk) {
    return {
      supported: false,
      code: '',
      label: 'WiFi receiver',
      hint: 'WiFi receiver supports Adafruit SSD1306 or Adafruit SH110X. Match Display + Library (not U8g2).',
    };
  }

  return {
    supported: true,
    code: generateWifiReceiverAdafruit(display, { ...board, id: config.board }, config.address, config.library),
    label: useAdafruitSH110x(display, config.library)
      ? 'WiFi receiver (Adafruit SH110X)'
      : 'WiFi receiver (Adafruit SSD1306)',
    hint: `${board.name} · ${display.name} @ ${config.address}. Edit WIFI_SSID/PASS in sketch. ESP joins your home WiFi — website + internet keep working.`,
  };
}

