// ─── MicroPython ──────────────────────────────────────────────────────────────
function generateMicroPython(frames, display, board, addr, isAnim, fps) {
  const { width, height } = display;
  const board_info = BOARDS[board];
  const addrInt = parseInt(addr, 16);

  const bitmaps = frames.map((f, i) => {
    const bytes = packBitmap(f, width, height);
    return `frame${i} = bytearray([${bytes.join(', ')}])
${frameCreditPy()}`;
  });

  const drawLogic = isAnim ? `
import time

frames = [${frames.map((_,i)=>`frame${i}`).join(', ')}]
idx = 0
while True:
    draw_bitmap(frames[idx])
    idx = (idx + 1) % len(frames)
    time.sleep(${(1/fps).toFixed(3)})` : `
draw_bitmap(frame0)`;

  return `# ${CODEGEN_ATTR}
# Board  : ${board_info.name}
# Display: ${display.name} @ ${addr}
#
${codegenSocialPy()}

from machine import Pin, I2C
import ssd1306
import framebuf

i2c = I2C(0, scl=Pin(${board_info.scl}), sda=Pin(${board_info.sda}))
display = ssd1306.SSD1306_I2C(${width}, ${height}, i2c, addr=${addrInt})

def draw_bitmap(data):
    buf = framebuf.FrameBuffer(bytearray(data), ${width}, ${height}, framebuf.MONO_HLSB)
    display.fill(0)
    display.blit(buf, 0, 0)
    display.show()

${bitmaps.join('\n')}
${drawLogic}
`;
}

