function receiverSerialLoopBody(drawCall) {
  return `
uint8_t rxState = 0;
uint16_t rxIdx = 0;

void loop() {
  while (Serial.available()) {
    uint8_t b = Serial.read();
    if (rxState == 0) {
      if (b == 0xAA) rxState = 1;
    } else if (rxState == 1) {
      if (b == 0xBB) { rxState = 2; rxIdx = 0; }
      else rxState = (b == 0xAA) ? 1 : 0;
    } else {
      buffer[rxIdx++] = b;
      if (rxIdx >= BUFFER_LEN) {
        ${drawCall}
        rxState = 0;
        rxIdx = 0;
      }
    }
#if defined(ESP8266) || defined(ESP32)
    yield();
#endif
  }
}`;
}

