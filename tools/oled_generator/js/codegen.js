/** Adafruit SSD1306 vs SH110X — SH1106 displays need Adafruit_SH110X / SH1106G */
function useAdafruitSH110x(display, library) {
  if (library === 'sh110x') return true;
  if (library === 'u8g2') return false;
  return !!(display && display.driver === 'SH1106');
}

function adafruitLibMeta(display, library) {
  const sh = useAdafruitSH110x(display, library);
  return {
    sh,
    include: sh ? 'Adafruit_SH110X.h' : 'Adafruit_SSD1306.h',
    className: sh ? 'Adafruit_SH1106G' : 'Adafruit_SSD1306',
    color: sh ? 'SH110X_WHITE' : 'SSD1306_WHITE',
    libLabel: sh ? 'Adafruit SH110X' : 'Adafruit SSD1306',
    beginExpr(addrExpr) {
      return sh
        ? `begin(${addrExpr}, true)`
        : `begin(SSD1306_SWITCHCAPVCC, ${addrExpr})`;
    },
  };
}

// Pack 2D pixel array into byte array (horizontal, MSB first — Adafruit format)
function packBitmap(frame, width, height) {
  const bytes = [];
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x += 8) {
      let byte = 0;
      for (let bit = 0; bit < 8; bit++) {
        if (x + bit < width && frame[y][x + bit]) {
          byte |= (0x80 >> bit);
        }
      }
      bytes.push(byte);
    }
  }
  return bytes;
}

// Format byte array as hex string rows
function formatBytes(bytes, cols = 16) {
  const lines = [];
  for (let i = 0; i < bytes.length; i += cols) {
    const chunk = bytes.slice(i, i + cols).map(b => '0x' + b.toString(16).padStart(2, '0'));
    lines.push('  ' + chunk.join(', '));
  }
  return lines.join(',\n');
}

